// Run by hand: node scripts/build-exercises.mjs. Writes src/data/exercises.json and src/data/SOURCE.md.
// Downloads free-exercise-db at a pinned commit (Unlicense). Never run at app runtime. To refresh, change COMMIT and review the diff.
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

export const COMMIT = 'f00c92c7dcf1216a928a52c3706c7ce8e2f71ed5';
const URL_RAW = `https://raw.githubusercontent.com/yuhonas/free-exercise-db/${COMMIT}/dist/exercises.json`;

const text = v => (typeof v === 'string' && v.trim() !== '' ? v : 'other');
const sorted = set => [...set].sort();

// Pure. Five fields per exercise; null/empty equipment or muscle becomes "other". Lists are read from the data ("other" always present).
export function trimDataset(raw) {
  const exercises = raw.map(e => ({ id: e.id, name: e.name, equipment: text(e.equipment), muscle: text(e.primaryMuscles?.[0]), category: text(e.category) }));
  return {
    exercises,
    muscles: sorted(new Set(['other', ...exercises.map(e => e.muscle)])),
    equipment: sorted(new Set(['other', ...exercises.map(e => e.equipment)])),
  };
}

const SOURCE = `# Exercise data source

\`exercises.json\` is generated by \`scripts/build-exercises.mjs\` from [free-exercise-db](https://github.com/yuhonas/free-exercise-db) (public domain, Unlicense), by yuhonas and contributors.

- Commit: \`${COMMIT}\`
- File: \`dist/exercises.json\`
- Kept per exercise: id, name, equipment, primary muscle (first entry), category. Null or empty equipment/muscle is stored as "other".
- Refresh only by hand: change COMMIT in the script, re-run, review the diff.
`;

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const res = await fetch(URL_RAW);
  if (!res.ok) throw new Error(`download failed: ${res.status}`);
  const out = trimDataset(await res.json());
  const dir = new URL('../src/data/', import.meta.url);
  writeFileSync(new URL('exercises.json', dir), JSON.stringify(out));
  writeFileSync(new URL('SOURCE.md', dir), SOURCE);
  console.log(`${out.exercises.length} exercises, ${out.muscles.length} muscles, ${out.equipment.length} equipment`);
}
